#!/usr/bin/env python3
"""Generate the C++ ROM table used by the built-in release preparer.

The table contains only file names, sizes, CRCs and interleave offsets. It
contains no game data. `romsets.py` remains the single source of truth.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from romsets import PDRIFT  # noqa: E402

KIND = {
    "flat": "RomInterleave::Flat",
    "w16": "RomInterleave::W16",
    "x64": "RomInterleave::X64",
}


def cstr(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    regions = PDRIFT["regions"]
    lines = [
        "// Generated by tools/gen_rom_table.py. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace likethewind {",
        "enum class RomInterleave { Flat, W16, X64 };",
        "struct RomFileSpec { const char *name; uint32_t size; uint32_t crc; const char *sha1; uint32_t offset; uint32_t copies; };",
        "struct RomRegionSpec { const char *name; RomInterleave kind; uint32_t size; uint8_t fill; const RomFileSpec *files; uint32_t file_count; };",
        "",
    ]

    for region, spec in regions.items():
        ident = region.capitalize()
        lines.append(f"static const RomFileSpec k{ident}Files[] = {{")
        for entry in spec["files"]:
            name, size, crc, sha1, offset = entry[:5]
            copies = entry[5] if len(entry) > 5 else 1
            lines.append(
                f"    {{{cstr(name)}, 0x{size:X}u, 0x{crc:08X}u, {cstr(sha1)}, "
                f"0x{offset:X}u, {copies}u}},"
            )
        lines.append("};")
        lines.append("")

    lines.append("static const RomRegionSpec kRomRegions[] = {")
    for region, spec in regions.items():
        ident = region.capitalize()
        fill = spec.get("fill", 0)
        lines.append(
            f"    {{{cstr(region)}, {KIND[spec['kind']]}, 0x{spec['size']:X}u, "
            f"0x{fill:02X}u, k{ident}Files, "
            f"sizeof(k{ident}Files) / sizeof(k{ident}Files[0])}},"
        )
    lines.append("};")
    lines.append("")
    lines.append("static constexpr uint32_t kRomRegionCount =")
    lines.append("    sizeof(kRomRegions) / sizeof(kRomRegions[0]);")
    lines.append("")
    lines.append("} // namespace likethewind")
    lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
